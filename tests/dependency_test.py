class TestInvalidDllName(unittest.TestCase):
    def test_invalid_dll_name_is_kept_as_unresolved(self):
        data = bytearray(PE_THREE_DIRECTORIES)
        # Set the VA-mode delay descriptor's szName so normalisation yields the
        # page-zero string, which is not a valid DOS filename.
        delay_rva = struct.unpack_from("<I", data, 0x190)[0]
        struct.pack_into("<I", data, delay_rva + 32 + 4, 0x10000000)
        with pefile.PE(data=bytes(data)) as pe:
            report = pe.get_dependency_evidence()
            self.assertIn("*invalid*", report.get_dlls())
            invalid = report.get_entries(dll="*invalid*")
            self.assertEqual(len(invalid), 1)
            self.assertEqual(invalid[0].dll, "*invalid*")
            self.assertFalse(invalid[0].dll_valid)
            self.assertIn(
                "invalid_dll_name",
                {d["reason"] for d in report.diagnostics},
            )
            # None DLLs, if any, never break filtering.
            self.assertEqual(report.get_entries(dll="missing.dll"), [])
            # The conflicting kernel32.dll Alpha entries are still reported.
            self.assertIn("kernel32.dll", report.get_conflicts())

class TestDamagedDependencyDirectories(unittest.TestCase):
    def test_damaged_delay_keeps_other_directories(self):
        with pefile.PE(data=PE_DAMAGED_DELAY) as pe:
            report = pe.get_dependency_evidence()
            # The damaged VA-mode descriptor is dropped, but the sibling
            # RVA-mode descriptor and all regular/bound results remain.
            self.assertEqual(
                [e.name for e in report.get_entries(directory="import", kind="symbol")],
                ["Alpha", "Beta"],
            )
            self.assertEqual(
                [
                    e.name
                    for e in report.get_entries(
                        directory="delay_import", kind="symbol"
                    )
                    if e.resolved
                ],
                ["Alpha", "Gamma"],
            )
            self.assertTrue(report.sources["bound_import"]["parsed"])
            self.assertEqual(
                {e.dll for e in report.get_entries(directory="bound_import")},
                {"kernel32.dll", "advapi32.dll"},
            )
            diagnostic = next(
                d for d in report.diagnostics
                if d["directory"] == "delay_import" and d.get("thunk_rva") is not None
            )
            self.assertEqual(diagnostic["reason"], "unreadable_hint_name")
            self.assertEqual(diagnostic["resolution_mode"], "va")

    def test_damaged_directory_is_marked_in_sources(self):
        with pefile.PE(data=PE_DAMAGED_DELAY) as pe:
            report = pe.get_dependency_evidence()
            self.assertEqual(report.sources["delay_import"]["entry_count"], 1)
            self.assertEqual(report.sources["delay_import"]["rva"], 0x4CC)

    def test_bad_pointer_keeps_confirmed_symbols(self):
        with pefile.PE(data=PE_BAD_DELAY_POINTER) as pe:
            report = pe.get_dependency_evidence()
            self.assertEqual(
                [e.name for e in report.get_entries(directory="import", kind="symbol")],
                ["Alpha", "Beta"],
            )
            unresolved = report.get_unresolved(directory="delay_import")
            # The RVA-mode descriptor has two bad hint/name pointers; the
            # untouched VA-mode descriptor still resolves and is not reported.
            self.assertEqual(len(unresolved), 2)
            for entry in unresolved:
                self.assertEqual(entry.reason, "unreadable_hint_name")
                self.assertIsNotNone(entry.detail)
                self.assertIsNotNone(entry.thunk_rva)
                self.assertIsNotNone(entry.thunk_offset)
            self.assertEqual(
                {e.dll for e in report.get_entries(directory="bound_import")},
                {"kernel32.dll", "advapi32.dll"},
            )

    def test_bad_pointer_is_preserved_in_conflict_summary(self):
        with pefile.PE(data=PE_BAD_DELAY_POINTER) as pe:
            report = pe.get_dependency_evidence()
            conflicts = report.get_conflicts(dll="kernel32.dll")
            self.assertIn("kernel32.dll", conflicts)
            unresolved = [
                c
                for c in conflicts["kernel32.dll"]
                if c.get("resolution") == "unresolved"
            ]
            self.assertEqual(len(unresolved), 1)
            conflict = unresolved[0]
            self.assertEqual(
                conflict["symbol"], ("unresolved", "unreadable_hint_name")
            )
            self.assertEqual(
                {r["reason"] for r in conflict["representations"]},
                {"unreadable_hint_name"},
            )
            # Both bad entries are kept, not merged into one.
            self.assertEqual(len(conflict["records"]["delay_import"]), 2)
            self.assertEqual(len(conflict["representations"]), 1)

