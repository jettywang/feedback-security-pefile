class TestDependencyEvidence(unittest.TestCase):
    def parse(self, data=PE_THREE_DIRECTORIES, **kwargs):
        pe = pefile.PE(data=data, **kwargs)
        return pe

    def test_all_three_directories_are_present(self):
        with self.parse() as pe:
            report = pe.get_dependency_evidence()
            self.assertEqual(
                set(report.sources),
                {"import", "delay_import", "bound_import"},
            )
            for source in report.sources.values():
                self.assertTrue(source["parsed"], source)
            self.assertEqual(report.sources["import"]["entry_count"], 1)
            self.assertEqual(report.sources["delay_import"]["entry_count"], 2)
            self.assertEqual(report.sources["bound_import"]["entry_count"], 1)

    def test_symbols_keep_directory_and_type(self):
        with self.parse() as pe:
            report = pe.get_dependency_evidence()
            imports = report.get_entries(directory="import", kind="symbol")
            delay = report.get_entries(directory="delay_import", kind="symbol")
            bound = report.get_entries(directory="bound_import", kind="dll_descriptor")

            self.assertEqual(
                [(e.dll, e.name, e.ordinal) for e in imports],
                [("kernel32.dll", "Alpha", None), ("kernel32.dll", "Beta", None)],
            )
            self.assertEqual(
                [(e.dll, e.name, e.ordinal) for e in delay],
                [
                    ("kernel32.dll", "Alpha", None),
                    ("kernel32.dll", "Gamma", None),
                    ("advapi32.dll", "Epsilon", None),
                ],
            )
            self.assertEqual(
                [(e.dll, e.time_date_stamp) for e in bound],
                [("kernel32.dll", 0xDEADBEEF), ("advapi32.dll", 0xFEEDFACE)],
            )
            for entry in imports + delay:
                self.assertEqual(entry.address_kind, "iat_slot_va")
                self.assertEqual(entry.address_base, "image_base")

    def test_same_dll_is_correlated_across_directories(self):
        with self.parse() as pe:
            report = pe.get_dependency_evidence()
            kernel32 = report.by_dll["kernel32.dll"]
            self.assertIn("import", {e.directory for e in kernel32})
            self.assertIn("delay_import", {e.directory for e in kernel32})
            self.assertIn("bound_import", {e.directory for e in kernel32})
            self.assertEqual(
                {e.directory for e in report.by_dll["advapi32.dll"]},
                {"delay_import", "bound_import"},
            )

    def test_conflicting_symbols_are_preserved_not_merged(self):
        with self.parse() as pe:
            report = pe.get_dependency_evidence()
            conflicts = report.get_conflicts(dll="kernel32.dll")
            self.assertIn("kernel32.dll", conflicts)
            alpha = [
                c for c in conflicts["kernel32.dll"] if c["symbol"] == ("name", "alpha")
            ]
            self.assertEqual(len(alpha), 1)
            representations = {
                (r["name"], r["hint"], tuple(r["sources"]))
                for r in alpha[0]["representations"]
            }
            self.assertEqual(len(representations), 2)
            records = alpha[0]["records"]
            self.assertEqual(records["import"][0]["name"], "Alpha")
            self.assertEqual(records["delay_import"][0]["name"], "Alpha")
            self.assertNotEqual(
                records["import"][0]["hint"], records["delay_import"][0]["hint"]
            )
            self.assertNotEqual(
                records["import"][0]["address"],
                records["delay_import"][0]["address"],
            )

    def test_bound_timestamp_is_not_identity(self):
        with self.parse() as pe:
            report = pe.get_dependency_evidence()
            bound = report.get_entries(directory="bound_import")
            for entry in bound:
                self.assertFalse(entry.timestamp_trusted)
                self.assertEqual(entry.address_kind, "none")
            # Two different timestamps do not create a conflict for the same DLL
            # and do not suppress the regular/delay evidence.
            self.assertEqual(len(report.get_entries(dll="kernel32.dll")), 5)
            self.assertEqual(
                [e.name for e in report.get_entries(dll="kernel32.dll", kind="symbol")],
                ["Alpha", "Beta", "Alpha", "Gamma"],
            )

    def test_bound_directory_does_not_participate_in_symbol_conflicts(self):
        with self.parse() as pe:
            report = pe.get_dependency_evidence()
            conflicts = report.get_conflicts()
            for group in conflicts.values():
                for conflict in group:
                    self.assertNotIn("bound_import", conflict["records"])


class TestSyntheticFixtureShape(unittest.TestCase):
    """Guard the fixture so report assertions stay meaningful."""

    def test_fixture_has_intended_directories(self):
        with pefile.PE(data=PE_THREE_DIRECTORIES) as pe:
            modules = {m.dll: m for m in pe.DIRECTORY_ENTRY_DELAY_IMPORT}
            self.assertEqual(set(modules), {b"kernel32.dll", b"advapi32.dll"})
            self.assertEqual(modules[b"kernel32.dll"].resolution_mode, "rva")
            self.assertEqual(modules[b"advapi32.dll"].resolution_mode, "va")
            self.assertEqual(
                [(m.name, m.struct.TimeDateStamp) for m in pe.DIRECTORY_ENTRY_BOUND_IMPORT],
                [(b"kernel32.dll", 0xDEADBEEF)],
            )
            self.assertEqual(
                [e.name for e in pe.DIRECTORY_ENTRY_BOUND_IMPORT[0].entries],
                [b"advapi32.dll"],
            )

    def test_fixture_delay_symbols_are_distinct(self):
        with pefile.PE(data=PE_THREE_DIRECTORIES) as pe:
            regular = {
                s.name: s.hint for s in pe.DIRECTORY_ENTRY_IMPORT[0].imports
            }
            delay = {
                s.name: s.hint
                for m in pe.DIRECTORY_ENTRY_DELAY_IMPORT
                if m.dll == b"kernel32.dll"
                for s in m.imports
            }
            self.assertEqual(regular[b"Alpha"], 1)
            self.assertEqual(delay[b"Alpha"], 11)
            self.assertIn(b"Gamma", delay)


class TestDelayImportAddressModes(unittest.TestCase):
    def test_rva_and_va_modes_are_reported_separately(self):
        with pefile.PE(data=PE_THREE_DIRECTORIES) as pe:
            modules = {m.dll: m for m in pe.DIRECTORY_ENTRY_DELAY_IMPORT}
            self.assertEqual(modules[b"kernel32.dll"].resolution_mode, "rva")
            self.assertEqual(modules[b"advapi32.dll"].resolution_mode, "va")

            report = pe.get_dependency_evidence()
            rva_entries = [
                e for e in report.get_entries(dll="kernel32.dll")
                if e.directory == "delay_import"
            ]
            va_entries = report.get_entries(dll="advapi32.dll", directory="delay_import")
            self.assertTrue(all(e.resolution_mode == "rva" for e in rva_entries))
            self.assertTrue(all(e.resolution_mode == "va" for e in va_entries))

            # The VA-mode descriptor stores absolute addresses; the reported
            # slot address must still be ImageBase + normalised RVA, never the
            # raw VA interpreted as an RVA.
            descriptor = modules[b"advapi32.dll"].struct
            normalised_iat = descriptor.pIAT
            self.assertLess(normalised_iat, pe.OPTIONAL_HEADER.SizeOfImage)
            self.assertEqual(
                va_entries[0].address,
                pe.OPTIONAL_HEADER.ImageBase + normalised_iat,
            )
            self.assertEqual(va_entries[0].address_base, "image_base")

    def test_va_mode_field_is_not_resolved_as_rva(self):
        """A raw VA-mode field must not be interpreted as an RVA."""
        raw_va = 0x10000558
        with pefile.PE(data=PE_THREE_DIRECTORIES) as pe:
            self.assertEqual(pe.classify_import_address(raw_va), "va")
            self.assertEqual(pe.classify_import_address(0x558), "rva")
            # The raw VA does not address the section when used as an RVA;
            # only normalisation makes it usable.
            self.assertIsNone(pe.get_section_by_rva(raw_va))
            self.assertIsNotNone(pe.get_section_by_rva(0x558))


